# modules/texts/announcement.py
"""
Разовый анонс запуска TopPsyGame по существующей базе cardbot.

Это НЕ воронка из modules/texts/platform.py. Разница принципиальная:
воронку человек открывает сам, а анонс приходит ему без спроса, то есть
является рекламной рассылкой по смыслу ст. 18 № 38-ФЗ. Поэтому анонс живёт
отдельным файлом, отправляется существующим механизмом постов и только тем,
чьё согласие такие сообщения покрывает.

Текст согласован заказчиком и приведён дословно. Меняются только ссылки:
вместо голых адресов — HTML-ссылки, чтобы UTM-метки не торчали в сообщении
простынёй из query-параметров.
"""
from urllib.parse import urlencode

from modules.texts.platform import PLATFORM_URL, UTM_MEDIUM, UTM_SOURCE

# Лендинг с описанием продукта. Анонс ведёт сначала сюда: аудитория cardbot
# знает «Карту дня», но не знает TopPsyGame, и ей нужно объяснение раньше формы
# регистрации. На главной много материалов об авторе и программе «Твой ход»,
# поэтому ссылка ведёт сразу в раздел платформы.
SITE_URL = "https://toppsygame.ru/"
SITE_ANCHOR = "platform"

# Отдельная кампания, а не utm_content внутри platform_launch: главный вопрос
# по анонсу — сколько человек дошло до регистрации именно после него, и это
# должно отделяться от воронки одним фильтром, а не вычитанием меток.
UTM_CAMPAIGN = "platform_announcement"

# Закрытый список: ссылка уходит во внешний сервис и попадает в его логи,
# поэтому ничего, кроме метки места клика, в ней быть не должно.
UTM_CONTENTS = ("site", "app")


def _with_utm(base: str, utm_content: str, anchor: str = "") -> str:
    """
    Адрес с UTM-метками. Якорь приклеивается ПОСЛЕ query-строки: в URL фрагмент
    всегда последний, и «/#platform?utm_source=...» означало бы, что параметры
    стали частью фрагмента и до аналитики не дошли.
    """
    if utm_content not in UTM_CONTENTS:
        raise ValueError(f"Недопустимый utm_content: {utm_content}")
    params = urlencode({
        "utm_source": UTM_SOURCE,
        "utm_medium": UTM_MEDIUM,
        "utm_campaign": UTM_CAMPAIGN,
        "utm_content": utm_content,
    })
    return f"{base}?{params}" + (f"#{anchor}" if anchor else "")


def site_url() -> str:
    """Лендинг, раздел платформы."""
    return _with_utm(SITE_URL, "site", SITE_ANCHOR)


def app_url() -> str:
    """Само приложение: регистрация и работа."""
    return _with_utm(PLATFORM_URL, "app")


# Заголовок нужен только админке: в сообщение он не попадает.
ANNOUNCEMENT_TITLE = "Анонс TopPsyGame"

# Подпись к картинке. Текст дословно согласован, видимые подписи ссылок
# совпадают с адресами из согласованного текста — метки скрыты в href.
#
# Разделители параметров оставлены как «&», а не «&amp;»: Telegram разбирает
# HTML снисходительно и «&utm_medium» сущностью не считает (нет закрывающей «;»),
# зато при обратном варианте риск хуже — если бы атрибуты не разэкранировались,
# в адрес уехало бы «&amp;» и метки молча перестали бы читаться аналитикой.
# Проверяется это предпросмотром: ссылку надо открыть и посмотреть адрес.
ANNOUNCEMENT_TEXT = (
    "🃏 У нас новость — появилась TopPsyGame!\n"
    "\n"
    "Мы запустили онлайн-платформу для работы с метафорическими картами "
    "и трансформационными играми.\n"
    "\n"
    "Теперь можно проводить МАК-сессии и игры прямо в браузере: выбирать "
    "инструменты, создавать игровые комнаты и приглашать участников.\n"
    "\n"
    "✨ Посмотрите, что получилось!\n"
    "\n"
    "Узнать о платформе:\n"
    '<a href="{site}">toppsygame.ru/#platform</a>\n'
    "\n"
    "Перейти в приложение:\n"
    '<a href="{app}">online.toppsygame.ru</a>'
)


def announcement_text() -> str:
    """Готовая подпись к посту с подставленными ссылками."""
    return ANNOUNCEMENT_TEXT.format(site=site_url(), app=app_url())
