from urllib.parse import urlencode

# Идентификатор кампании. Состояние пользователя хранится в разрезе кампании,
# поэтому следующая кампания получит новый id и не затрёт историю этой.
CAMPAIGN_ID = "platform_launch"

# Корень приложения. Остальные маршруты платформы (/conduct, /tools, /sessions/new)
# закрыты AuthBoundary, то есть анонимному посетителю всё равно покажут вход, а
# глубокая ссылка после авторизации теряется. Поэтому все кнопки ведут на корень:
# это единственный проверенный маршрут. Шаг воронки различается через utm_content.
PLATFORM_URL = "https://online.toppsygame.ru/"

UTM_SOURCE = "cardbot"
UTM_MEDIUM = "telegram"
UTM_CAMPAIGN = CAMPAIGN_ID

# Допустимые значения utm_content: только метка роли и шага воронки. Telegram ID и
# любых других персональных данных в ссылке нет и быть не должно — ссылка уходит
# во внешний сервис и попадает в его логи.
UTM_CONTENTS = (
    "facilitator", "explorer",
    "facilitator_d2", "explorer_d2",
    "facilitator_d5", "explorer_d5",
)


def platform_url(utm_content: str) -> str:
    """Ссылка на платформу с UTM-метками. Порядок параметров фиксирован."""
    if utm_content not in UTM_CONTENTS:
        raise ValueError(f"Недопустимый utm_content: {utm_content}")
    params = urlencode({
        "utm_source": UTM_SOURCE,
        "utm_medium": UTM_MEDIUM,
        "utm_campaign": UTM_CAMPAIGN,
        "utm_content": utm_content,
    })
    return f"{PLATFORM_URL}?{params}"


